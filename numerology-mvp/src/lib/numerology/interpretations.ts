/**
 * Get detailed interpretation for a specific number and position
 */
export function getDetailedInterpretation(
    position: 'lifePath' | 'personalYear',
    number: number
): string {
    const interpretations = DETAILED_INTERPRETATIONS[position];
    if (!interpretations) return '';

    const interpretation = interpretations[number as keyof typeof interpretations];
    if (!interpretation) return '';

    if (typeof interpretation === 'string') {
        return interpretation;
    }

    return interpretation.detailed || interpretation.summary || '';
}
